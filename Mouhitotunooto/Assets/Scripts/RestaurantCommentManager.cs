    /// <summary>
    /// レストランの料理に対するコメント管理クラス
    /// 料理名に対して1対1で気の利いたセリフを提供する
    /// </summary>
    public static class RestaurantCommentManager
    {
        /// <summary>
        /// 料理名に対するコメント（セリフ）を取得
        /// </summary>
        /// <param name="dishName">料理名</param>
        /// <returns>料理に対するコメント。見つからない場合はデフォルトのコメントを返す</returns>
        public static string GetCommentForDish(string dishName)
        {
            if (string.IsNullOrEmpty(dishName))
            {
                return GetDefaultComment();
            }

            // 料理名とコメントの対応表
            if (dishComments.ContainsKey(dishName))
            {
                return dishComments[dishName];
            }

            // 部分一致で検索（例：「天ぷら」が含まれる料理）
            foreach (var kvp in dishComments)
            {
                if (dishName.Contains(kvp.Key) || kvp.Key.Contains(dishName))
                {
                    return kvp.Value;
                }
            }

            // デフォルトのコメントを返す
            return GetDefaultComment();
        }

